// Build display data from the reviewed screenplay; production pages load no Markdown parser.
const fs=require('node:fs');
const source=fs.readFileSync('docs/quest/GOIMON_CHAPTER1_NOVEL_INTEGRATED_V5.md','utf8');
const scenes=[];let scene=null;
const backgrounds=['forest','forest','forest','forest','stele','forest','forest','forest','forest','forest','forest','forest','forest','forest','stele','memory','memory','mist','stele','forest'];
for(const line of source.split('\n')){
 const head=/^## (ch1\.\d+)｜(.+)$/.exec(line);
 if(head){scene={id:head[1],title:head[2],background:backgrounds[scenes.length],lines:[]};scenes.push(scene);continue;}
 if(/^## /.test(line)){scene=null;continue;}if(!scene)continue;
 const match=/^【([^】]+)】(.+)$/.exec(line);if(!match)continue;
 const [,speaker,text]=match;
 if(speaker==='演出'||speaker==='遷移'){
  if(scene.id==='ch1.06'&&text.startsWith('既存STAGE0'))scene.lines.push({event:'tutorial'});
  if(scene.id==='ch1.06'&&text.startsWith('既存の体験用10個'))scene.lines.push({event:'gift'});
  continue;
 }
 scene.lines.push({speaker:speaker==='地の文'?'':speaker,text:text.replace(/^「|」$/g,'')});
}
const battleScenes={7:1,9:2,11:3,13:4,15:5,18:'mist'};
for(const [n,id]of Object.entries(battleScenes))scenes[Number(n)-1].lines.push({event:'battle',battleId:id});
for(const s of scenes)s.lines.forEach((l,i)=>l.id=s.id+'.'+String(i+1).padStart(3,'0'));
if(scenes.length!==20)throw Error('Expected 20 scenes');
const data={version:1,scriptVersion:'v5.1',title:'聞こえた言葉',scenes};
fs.writeFileSync('battle-prototype/chapter1_data.js','// Generated by scripts/build-chapter1.cjs from integrated V5.\n(function(root){const data='+JSON.stringify(data,null,2)+';if(typeof module!=="undefined")module.exports=data;else root.GoimonChapter1Data=data;})(typeof window!=="undefined"?window:globalThis);\n');
